defmodule BezgelorData.Spell4Catalog do
  @moduledoc """
  Correctly decoded, read-only reference subset of original ClientDB tables.

  Generated by tools/extract_spell4_combat.exs. Coverage is explicit, never
  inferred from a spell name. Raw records use string keys and preserve all
  original fields. Presence in this catalog does not authorize execution.
  """

  @path Path.expand("../../priv/data/spell4_combat_reference.json", __DIR__)
  @external_resource @path
  @reference @path |> File.read!() |> Jason.decode!()
  @tables Map.new(@reference["tables"], fn {name, table} ->
            {name, Map.new(table["rows"], &{&1["ID"], &1})}
          end)
  @effects @tables["Spell4Effects"] |> Map.values() |> Enum.group_by(& &1["spellId"])

  def roots, do: @reference["roots"]
  def covered?(id), do: Map.has_key?(@tables["Spell4"], id)
  def spell_ids, do: @tables["Spell4"] |> Map.keys() |> Enum.sort()
  def row(table, id), do: @tables |> Map.fetch!(table) |> Map.get(id)
  def rows(table), do: @tables |> Map.fetch!(table) |> Map.values() |> Enum.sort_by(& &1["ID"])
  def effects(id), do: @effects |> Map.get(id, []) |> Enum.sort_by(&{&1["orderIndex"], &1["ID"]})
  def phases(id), do: Enum.filter(rows("SpellPhase"), &(&1["spell4IdOwner"] == id))
  def thresholds(id), do: Enum.filter(rows("Spell4Thresholds"), &(&1["spell4IdParent"] == id))
  def metadata(table), do: Map.drop(@reference["tables"][table], ["rows"])

  @spell_fields [
    :description,
    :spell4BaseIdBaseSpell,
    :tierIndex,
    :ravelInstanceId,
    :castTime,
    :spellDuration,
    :spellCoolDown,
    :targetMinRange,
    :targetMaxRange,
    :targetVerticalRange,
    :casterInnateRequirement0,
    :casterInnateRequirement1,
    :casterInnateRequirementValue0,
    :casterInnateRequirementValue1,
    :casterInnateRequirementEval0,
    :casterInnateRequirementEval1,
    :targetBeginInnateRequirement,
    :targetBeginInnateRequirementValue,
    :targetBeginInnateRequirementEval,
    :innateCostType0,
    :innateCostType1,
    :innateCost0,
    :innateCost1,
    :innateCostEMMId0,
    :innateCostEMMId1,
    :channelInitialDelay,
    :channelMaxTime,
    :channelPulseTime,
    :localizedTextIdActionBarTooltip,
    :stackPriority,
    :spell4VisualGroupId,
    :spell4IdCastEvent00,
    :spell4IdCastEvent01,
    :spell4IdCastEvent02,
    :spell4IdCastEvent03,
    :spell4ReagentId00,
    :spell4ReagentId01,
    :spell4ReagentId02,
    :spell4RunnerId00,
    :spell4RunnerId01,
    :runnerTargetTypeEnum00,
    :runnerTargetTypeEnum01,
    :prerequisiteIdRunner00,
    :prerequisiteIdRunner01,
    :abilityChargeCount,
    :abilityRechargeTime,
    :abilityRechargeCount,
    :thresholdTime,
    :abilityPointCost,
    :trainingCost,
    :spellChannelFlags,
    :ignoreFollowTimeMs,
    :spell4IdMechanicAlternateSpell,
    :spell4IdPetSwitch,
    :spell4TagId00,
    :spell4TagId01,
    :spell4TagId02,
    :spell4TagId03,
    :spell4TagId04,
    :localizedTextIdCasterIconSpellText,
    :localizedTextIdPrimaryTargetIconSpellText,
    :localizedTextIdSecondaryTargetIconSpellText,
    :localizedTextIdLASTier,
    :localizedTextIdTooltipCastInfo,
    :localizedTextIdTooltipCostInfo,
    :tooltipCastTime,
    :spell4AoeTargetConstraintsId,
    :spell4ConditionsIdCaster,
    :spell4ConditionsIdTarget,
    :spell4CCConditionsIdCaster,
    :spell4CCConditionsIdTarget,
    :spellCoolDownIdGlobal,
    :spellCoolDownId00,
    :spellCoolDownId01,
    :spellCoolDownId02,
    :spell4GroupListId,
    :missileSpeed,
    :minMissileSpeed,
    :spell4ClientMissileId00,
    :spell4ClientMissileId01,
    :spell4ClientMissileId02,
    :spell4ClientMissileId03,
    :spell4ClientMissileId04,
    :spell4ClientMissileId05,
    :globalCooldownEnum,
    :propertyFlags,
    :uiFlags,
    :spell4StackGroupId,
    :prerequisiteIdCasterCast,
    :prerequisiteIdTargetCast,
    :prerequisiteIdCasterPersistence,
    :prerequisiteIdTargetPersistence,
    :castEventConditionEnum00,
    :castEventConditionEnum01,
    :castEventConditionEnum02,
    :castEventConditionEnum03,
    :castEventTargetFlags00,
    :castEventTargetFlags01,
    :castEventTargetFlags02,
    :castEventTargetFlags03,
    :spellCastStealthChange,
    :prerequisiteIdAoeTarget,
    :prerequisiteIdAoePreferredTarget
  ]

  @doc "Corrected Spell4 fields for existing consumers; no executable effects."
  def spell_entry(id) do
    case row("Spell4", id) do
      nil ->
        :error

      raw ->
        entry = Map.new(@spell_fields, fn key -> {key, raw[Atom.to_string(key)]} end)
        {:ok, Map.put(entry, :id, raw["ID"])}
    end
  end
end
